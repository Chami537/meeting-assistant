class HeartbeatCommand(StrEnum):
    """Cancellation is not a command: the attempt becomes CANCELED and the next call gets 409 CANCELED."""

    CONTINUE = "CONTINUE"
    STOP_AND_UPLOAD = "STOP_AND_UPLOAD"


class ConflictReason(StrEnum):
    """Reason carried by every 409 sent to a Worker (design doc §5.2). The Worker stops and leaves on any
    409 except OUT_OF_ORDER, which only asks it to resend events from expected_seq."""

    EXPIRED = "EXPIRED"
    FINISHED = "FINISHED"
    CANCELED = "CANCELED"
    NOT_OWNER = "NOT_OWNER"
    OUT_OF_ORDER = "OUT_OF_ORDER"


