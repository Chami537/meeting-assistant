"""Hand-written from the design doc §5.3, NOT derived from the code: for a LIVE_MEETING task whose time guards
are satisfied, which statuses accept each trigger. Tests compare the state machine against this table."""

from app.domain.state_machine import TriggerType as T
from meeting_protocol import TaskStatus as S

IN_ATTEMPT = {S.JOINING, S.WAITING_ROOM, S.IN_MEETING, S.AWAITING_RECORDING_APPROVAL, S.RECORDING}
NOT_TERMINAL = set(S) - {S.COMPLETED, S.CANCELED, S.FAILED}
STOPPABLE = NOT_TERMINAL - {S.UPLOADING, S.TRANSCRIBING, S.SUMMARIZING}

LIVE_ALLOWED: dict[T, set[S]] = {
    T.DETAILS_COMPLETE: {S.AWAITING_DETAILS},
    T.CONSENT_GRANTED: {S.AWAITING_CONSENT},
    T.DISPATCH_DUE: {S.SCHEDULED},
    T.LEASE_CLAIMED: {S.DISPATCHING},
    T.DISPATCH_DEADLINE_PASSED: {S.DISPATCHING},
    T.DISPATCH_FAILED: {S.DISPATCHING},
    T.ENTERED_WAITING_ROOM: {S.JOINING},
    T.JOINED: {S.JOINING, S.WAITING_ROOM},
    T.RECORDING_NOTICE_SENT: {S.IN_MEETING},
    T.RECORDING_NOTICE_FAILED: {S.IN_MEETING},
    T.RECORDING_APPROVED: {S.AWAITING_RECORDING_APPROVAL},
    T.MEETING_ENDED: IN_ATTEMPT,
    T.RECORDING_LIMIT_REACHED: {S.RECORDING},
    T.ATTEMPT_FAILED: IN_ATTEMPT,  # with a code valid everywhere, e.g. WORKER_LOST
    T.LEASE_EXPIRED: IN_ATTEMPT,
    T.RETRY_DUE: {S.RETRY_WAIT},
    T.STOP_REQUESTED: STOPPABLE,
    T.CANCEL_REQUESTED: NOT_TERMINAL,
    T.UPLOAD_COMPLETE: {S.UPLOADING},
    T.UPLOAD_EMPTY: {S.UPLOADING},
    T.UPLOAD_DEADLINE_PASSED: {S.UPLOADING},
    T.UPLOAD_INVALID: set(),  # only uploads and forwarded minutes
    T.TRANSCRIPTION_DONE: {S.TRANSCRIBING},
    T.SUMMARY_DONE: {S.SUMMARIZING},
    T.JOB_FAILED: {S.TRANSCRIBING, S.SUMMARIZING},  # with the code matching the stage
    T.INTAKE_EXPIRED: {S.AWAITING_DETAILS, S.AWAITING_CONSENT},
}

assert set(LIVE_ALLOWED) == set(T)
