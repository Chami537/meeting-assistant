"""Numerals to digits in the transcription service. The sentences are made up in the shape of recognized
earnings-call speech (the evaluation recordings are not part of this repository), plus everyday speech that
must not turn into wrong exact numbers."""

import pytest

from asr_service.itn import itn


@pytest.mark.parametrize(
    ("spoken", "written"),
    [
        ("二零二五年全年收入达到三千五百二十九万元。", "2025年全年收入达到3529万元。"),
        ("二零二三年", "2023年"),
        ("同比增长超过百分之七十八。", "同比增长超过78%。"),
        ("同比增长了百分之一百二十四", "同比增长了124%"),
        ("毛利率只有百分之三点五", "毛利率只有3.5%"),
        ("其中XB幺零零二长效缓释片", "其中XB1002长效缓释片"),
        ("X B幺零幺七项目。", "X B1017项目。"),
        ("编号零零九", "编号009"),
        ("区号零二一", "区号021"),
        ("九零后", "90后"),
        ("大概一千六百这个用户", "大概1600这个用户"),
        ("大概一千六的用户", "大概1600的用户"),
        ("两百五", "250"),
        ("一百零五", "105"),
        ("两千零二十五", "2025"),
        ("每件十到十三块钱之间", "每件10到13块钱之间"),
        ("三到五年", "3到5年"),
        ("可以完成两千台的交付", "可以完成2000台的交付"),
        ("七月底", "7月底"),
        ("四月二十八日发布", "4月28日发布"),
        ("十二月", "12月"),
        ("应该在二八年的一季度", "应该在28年的一季度"),
        ("面积是一万三千五百平方米。", "面积是13500平方米。"),
        ("产能能达到一万二千台", "产能能达到12000台"),
        ("三百万", "300万"),
        ("一点五万", "1.5万"),
        ("海外是占百分之四十五以上", "海外是占45%以上"),
        ("第十四期", "第14期"),
        ("百分之零点五", "0.5%"),
        ("零点五亿", "0.5亿"),
        ("十月", "10月"),
        ("十月份", "10月份"),
        ("十一月", "11月"),
        ("二月", "2月"),
        ("二十多", "20多"),
        ("一百多个", "100多个"),
        ("一千二", "1200"),
        ("两千三百万", "2300万"),
        ("第三十二页", "第32页"),
        ("第十一个", "第11个"),
        ("二零年", "20年"),
        ("一九年", "19年"),
        ("唯一到三月", "唯一到3月"),
    ],
)
def test_numbers_become_digits(spoken, written):
    assert itn(spoken) == written


